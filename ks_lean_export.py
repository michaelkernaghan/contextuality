"""Export KS sets and case-split refutations to Lean (lean-ks/KS/*.lean).

For each named set this writes the rays (coordinates a + b sqrt(d) as integer pairs) and a
certificate tree found by a small DPLL search.  Lean recomputes orthogonality from the
coordinates and checks the tree with KS.check, whose soundness is proved in KS/Basic.lean.
Nothing computed here is trusted by Lean: a wrong tree simply fails to check.

Usage:  python ks_lean_export.py              (CK31 and Peres33 into lean-ks/KS/)
        python ks_lean_export.py eisenstein   (33 Eisenstein rays into lean/Cyclotomic6n.lean,
                                               between the BEGIN/END GENERATED markers)
"""
import sys
from pathlib import Path

import ks_bpqs_exact as B

HERE = Path(__file__).resolve().parent
sys.setrecursionlimit(10000)


def refute(n, pairs, triads):
    adj = [set() for _ in range(n)]
    for i, j in pairs:
        adj[i].add(j)
        adj[j].add(i)
    tri_of = [[] for _ in range(n)]
    for t in triads:
        for r in t:
            tri_of[r].append(t)
    nodes = [0]

    def go(val):
        nodes[0] += 1
        for i, j in pairs:                                  # violated already?
            if val.get(i) is True and val.get(j) is True:
                return "(.pair %d %d)" % (i, j)
        for t in triads:
            if all(val.get(r) is False for r in t):
                return "(.triad %d %d %d)" % t
        free = [v for v in range(n) if v not in val]
        assert free, "total assignment without conflict: the set is colourable"
        pick = None
        for v in free:                                      # forced false: a true neighbour
            if any(val.get(u) is True for u in adj[v]):
                pick = v
                break
        if pick is None:
            for v in free:                                  # forced true: triad with two false
                if any(sum(val.get(r) is False for r in t) == 2 for t in tri_of[v]):
                    pick = v
                    break
        if pick is None:
            pick = max(free, key=lambda v: (len(tri_of[v]), len(adj[v])))
        a = go({**val, pick: True})
        b = go({**val, pick: False})
        return "(.split %d %s %s)" % (pick, a, b)

    return go({}), nodes[0]


def emit(name, title, d, coords, pairs, triads):
    cert, nodes = refute(len(coords), pairs, triads)
    rays = ",\n  ".join("(" + ", ".join("(%d, %d)" % c for c in ray) + ")" for ray in coords)
    text = """import KS.Basic

/-! %s

Generated by ks_lean_export.py.  %d rays, %d orthogonal pairs, %d triads; certificate with
%d nodes.  Coordinates `(a, b)` mean `a + b*sqrt(%d)`. -/
namespace KS.%s

def rays : List Ray := [
  %s]

def sys : Sys := sysOf %d rays

def cert : Cert :=
  %s

set_option maxRecDepth 1000000 in
theorem check_ok : check sys [] cert = true := by decide

/-- The %d rays above admit no Kochen-Specker colouring. -/
theorem uncolourable : Uncolourable sys := uncolourable_of_check sys cert check_ok

end KS.%s
""" % (title, len(coords), len(pairs), len(triads), nodes, d, name, rays, d, cert,
       len(coords), name)
    out = HERE / "lean-ks" / "KS" / ("%s.lean" % name)
    out.write_text(text, encoding="utf-8", newline="\n")
    print("%s: %d rays, %d pairs, %d triads, certificate %d nodes -> %s"
          % (name, len(coords), len(pairs), len(triads), nodes, out.name))


def from_set(key, deg2):
    rays, orth, bases = B.load_set(key)
    coords = []
    for ray in rays:
        row = []
        for x in ray:
            c = list(x.c) + [0, 0]
            assert all(v.denominator == 1 for v in x.c), "non-integral coordinate"
            assert deg2 or c[1] == 0
            row.append((int(c[0]), int(c[1])))
        coords.append(tuple(row))
    pairs = sorted(tuple(sorted(p)) for p in orth)
    return coords, pairs, sorted(bases)


BEGIN = "-- BEGIN GENERATED by ks_lean_export.py (eisenstein33)"
END = "-- END GENERATED (eisenstein33)"


def emit_eisenstein(path):
    """Replace the block between BEGIN and END in lean/Cyclotomic6n.lean.

    Coordinates (a, b) mean a + b*omega with omega^2 = -1 - omega, the representation of
    ks_recertify_v10.FW; the Lean side recomputes orthogonality in Z[omega]."""
    coords, pairs, triads = from_set("eisenstein33", True)
    cert, nodes = refute(len(coords), pairs, triads)
    rays = ",\n  ".join("(" + ", ".join("(%d, %d)" % c for c in ray) + ")" for ray in coords)
    block = """%s
/-- Generated: %d rays, %d orthogonal pairs, %d triads; certificate with %d nodes.
    Coordinates `(a, b)` mean `a + b * omega`. -/
def rays : List ERay := [
  %s]

def cert : Cert :=
  %s
%s""" % (BEGIN, len(coords), len(pairs), len(triads), nodes, rays, cert, END)
    text = path.read_text(encoding="utf-8")
    i, j = text.index(BEGIN), text.index(END)
    assert text.count(BEGIN) == 1 and text.count(END) == 1 and i < j
    path.write_text(text[:i] + block + text[j + len(END):], encoding="utf-8", newline="\n")
    print("eisenstein33: %d rays, %d pairs, %d triads, certificate %d nodes -> %s"
          % (len(coords), len(pairs), len(triads), nodes, path.name))


def main():
    if sys.argv[1:] == ["eisenstein"]:
        emit_eisenstein(HERE / "lean" / "Cyclotomic6n.lean")
        return
    c, p, t = from_set("ck31", False)
    emit("CK31", "The 31 rays of Conway and Kochen, integer coordinates.", 2, c, p, t)
    c, p, t = from_set("peres33", True)
    emit("Peres33", "The 33 rays of Peres, coordinates in Z[sqrt 2].", 2, c, p, t)


if __name__ == "__main__":
    main()
