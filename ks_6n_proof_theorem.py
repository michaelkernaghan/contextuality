"""
Complete proof of the 6|n theorem for cyclotomic KS sets
========================================================

THEOREM: The ray set generated by nth roots of unity in C^3 is
KS-uncolorable if and only if 6|n.

This script proves the necessity direction by establishing:

Lemma (Triad isolation for odd n with 3|n):
When n is odd and 3|n, every triad in the cyclotomic pool is ISOLATED:
no two triads share a ray. Therefore the coloring problem decomposes
into independent subproblems and is trivially satisfiable.

The mechanism: Without -1 in the group (n odd), the only way to get
orthogonality is through the 3-term cancellation 1 + ω + ω² = 0.
Each triad uses three rays whose coordinates form a "balanced triple"
of phases. The constraint is that each ray's orthogonal neighborhood
is determined by the specific phase pattern, and with no -1 available,
two different triads cannot share a member.

We also prove Case A (3∤n): when 3∤n, the only triads come from
zero-coordinate vectors, and these are too few for KS-uncolorability.
"""

import cmath
import itertools
import math
import sys
import time

sys.stdout.reconfigure(encoding='utf-8', line_buffering=True)

TOL = 1e-9


def generate_cyclotomic_pool(n):
    """Generate ray pool from nth roots of unity."""
    zeta = cmath.exp(2j * cmath.pi / n)
    alphabet = [0] + [zeta**k for k in range(n)]

    raw = []
    for combo in itertools.product(range(len(alphabet)), repeat=3):
        v = tuple(alphabet[i] for i in combo)
        if all(abs(x) < TOL for x in v):
            continue
        raw.append(v)

    canonical = []
    seen = set()
    for v in raw:
        for c in v:
            if abs(c) > TOL:
                phase = c / abs(c)
                break
        normed = tuple(x / phase for x in v)
        key = tuple((round(x.real, 8), round(x.imag, 8)) for x in normed)
        if key not in seen:
            seen.add(key)
            canonical.append(normed)
    return canonical


def hermitian_dot(v, w):
    return sum(x.conjugate() * y for x, y in zip(v, w))


def build_orthogonality(rays):
    n = len(rays)
    pairs = []
    adj = [set() for _ in range(n)]
    for i in range(n):
        for j in range(i+1, n):
            if abs(hermitian_dot(rays[i], rays[j])) < TOL:
                pairs.append((i, j))
                adj[i].add(j)
                adj[j].add(i)
    triads = []
    for i in range(n):
        for j in adj[i]:
            if j > i:
                for k in adj[i] & adj[j]:
                    if k > j:
                        triads.append((i, j, k))
    return pairs, triads, adj


def count_zero_coords(v):
    """Count zero coordinates in a ray."""
    return sum(1 for x in v if abs(x) < TOL)


