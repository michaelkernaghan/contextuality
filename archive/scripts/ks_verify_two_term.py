"""Exact check of the two-term (trace-zero) cancellation gap raised by Frembs.

Question: in the raw two-letter pools {0, +-1, +-x} for x = sqrt(2) and x = sqrt(-2),
how many orthogonal pairs arise from a TWO-term vanishing sum (one coordinate of the
Hermitian product is zero) versus a THREE-term sum?

The paper's Table `tab:two-element` enumerates three-term zero-sums only. If the
Z[sqrt(-2)] pool contains orthogonalities generated by the two-term identity
x + conj(x) = 0 (i.e. Tr(x) = 0), that class is absent from the enumeration.

Exact arithmetic throughout: elements of Q(sqrt(d)) are Fraction pairs (a, b) = a + b*sqrt(d).
"""

from fractions import Fraction
from itertools import combinations, product


class QF:
    """Element a + b*sqrt(d) of the quadratic field Q(sqrt(d))."""

    __slots__ = ("a", "b", "d")

    def __init__(self, a, b, d):
        self.a = Fraction(a)
        self.b = Fraction(b)
        self.d = d

    def __mul__(self, o):
        return QF(self.a * o.a + self.b * o.b * self.d,
                  self.a * o.b + o.a * self.b, self.d)

    def __add__(self, o):
        return QF(self.a + o.a, self.b + o.b, self.d)

    def __sub__(self, o):
        return QF(self.a - o.a, self.b - o.b, self.d)

    def conj(self):
        # Hermitian conjugation: nontrivial only when sqrt(d) is imaginary (d < 0).
        return QF(self.a, -self.b, self.d) if self.d < 0 else QF(self.a, self.b, self.d)

    def is_zero(self):
        return self.a == 0 and self.b == 0

    def inv(self):
        n = self.a * self.a - self.b * self.b * self.d
        return QF(self.a / n, -self.b / n, self.d)

    def __eq__(self, o):
        return self.a == o.a and self.b == o.b

    def __hash__(self):
        return hash((self.a, self.b))

    def __repr__(self):
        if self.b == 0:
            return str(self.a)
        s = "sqrt(%d)" % self.d
        if self.a == 0:
            return ("-" if self.b < 0 else "") + (s if abs(self.b) == 1 else "%s*%s" % (abs(self.b), s))
        return "%s%s%s" % (self.a, "+" if self.b > 0 else "-",
                           s if abs(self.b) == 1 else "%s*%s" % (abs(self.b), s))


def alphabet(d):
    z = QF(0, 0, d)
    one = QF(1, 0, d)
    mone = QF(-1, 0, d)
    g = QF(0, 1, d)
    mg = QF(0, -1, d)
    return [z, one, mone, g, mg]


def same_ray(v, w):
    """True iff v and w span the same projective ray (w = lambda*v)."""
    i = next((k for k in range(3) if not v[k].is_zero()), None)
    if i is None:
        return False
    if w[i].is_zero():
        return False
    lam = w[i] * v[i].inv()
    return all((lam * v[k]) == w[k] for k in range(3))


def build_pool(d, alpha=None):
    raw = [v for v in product(alpha or alphabet(d), repeat=3)
           if not all(c.is_zero() for c in v)]
    rays = []
    for v in raw:
        if not any(same_ray(v, r) for r in rays):
            rays.append(v)
    return rays


def terms(v, w):
    """The three individual terms conj(v_k)*w_k of the Hermitian product."""
    return [v[k].conj() * w[k] for k in range(3)]


def analyse(d, label, alpha=None):
    rays = build_pool(d, alpha)
    pairs, two_term, three_term, trace_zero = [], 0, 0, []
    for i, j in combinations(range(len(rays)), 2):
        t = terms(rays[i], rays[j])
        s = t[0] + t[1] + t[2]
        if not s.is_zero():
            continue
        pairs.append((i, j))
        nz = [x for x in t if not x.is_zero()]
        if len(nz) == 2:
            two_term += 1
        elif len(nz) == 3:
            three_term += 1
        # Is this orthogonality CONJUGATION-DEPENDENT?  Re-evaluate the same pair
        # with the bilinear (no-conjugate) product.  If it still vanishes, the
        # cancellation is available to any generator of the same shape -- e.g.
        # x - x = 0 -- and is not evidence of a trace condition.  If it vanishes
        # only under the Hermitian product, it exists solely because conj(x) != x,
        # which for the two-letter alphabet means Tr(x) = 0.
        bil = rays[i][0] * rays[j][0] + rays[i][1] * rays[j][1] + rays[i][2] * rays[j][2]
        if not bil.is_zero():
            trace_zero.append((i, j, len(nz)))

    adj = {i: set() for i in range(len(rays))}
    for i, j in pairs:
        adj[i].add(j)
        adj[j].add(i)
    triads = sum(1 for i, j in pairs for k in adj[i] & adj[j] if k > j)

    print("=" * 66)
    print("%s   alphabet {0, +-1, +-sqrt(%d)}" % (label, d))
    print("=" * 66)
    print("  rays            : %d" % len(rays))
    print("  orthogonal pairs: %d" % len(pairs))
    print("  triads          : %d" % triads)
    print("  pairs from a TWO-term vanishing sum  : %d" % two_term)
    print("  pairs from a THREE-term vanishing sum: %d" % three_term)
    print("  pairs with disjoint support (all terms 0): %d"
          % (len(pairs) - two_term - three_term))
    print("  CONJUGATION-DEPENDENT pairs (vanish only under the")
    print("    Hermitian product, i.e. require conj(x) != x): %d" % len(trace_zero))
    if trace_zero:
        by_len = {}
        for _, _, n in trace_zero:
            by_len[n] = by_len.get(n, 0) + 1
        print("      by sum length: %s"
              % ", ".join("%d-term: %d" % (k, v) for k, v in sorted(by_len.items())))
        i, j, _ = trace_zero[0]
        print("      example: %s  _|_  %s" % (list(rays[i]), list(rays[j])))
    return rays, pairs, trace_zero


def probe(d, label):
    """The specific pair Frembs names: <(0,1,x),(0,x,1)> = x + conj(x)."""
    z, one, g = QF(0, 0, d), QF(1, 0, d), QF(0, 1, d)
    v, w = (z, one, g), (z, g, one)
    t = terms(v, w)
    s = t[0] + t[1] + t[2]
    print("  probe <(0,1,x),(0,x,1)> = %s  ->  %s"
          % (s, "ORTHOGONAL" if s.is_zero() else "not orthogonal"))
    print("  Tr(x) = x + conj(x) = %s" % (g + g.conj()))


for d, label in ((2, "Peres        Z[sqrt(2)] "), (-2, "Complex quad Z[sqrt(-2)]")):
    analyse(d, label)
    probe(d, label)
    print()

# Control: the Gaussian modulus-2 realisation uses the generator 1+i, whose
# trace is 2, NOT 0.  Alphabet {0, +-1, +-i, +-(1+i)} over Q(i).
gauss = [QF(0,0,-1), QF(1,0,-1), QF(-1,0,-1), QF(0,1,-1),
         QF(0,-1,-1), QF(1,1,-1), QF(-1,-1,-1)]
analyse(-1, "Gaussian     Z[i], alphabet {0,+-1,+-i,+-(1+i)}", gauss)
g = QF(1,1,-1)
print("  Tr(1+i) = %s      |1+i|^2 = %s" % (g + g.conj(), (g.conj()*g)))
i_ = QF(0,1,-1)
print("  Tr(i)   = %s      |i|^2   = %s" % (i_ + i_.conj(), (i_.conj()*i_)))
