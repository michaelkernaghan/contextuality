# PHASE 1: Vanishing sum characterization
# ============================================================

def analyze_vanishing_sums(n_max=60):
    """
    Prove: ζ^a + ζ^b + ζ^c = 0 for ζ = e^{2πi/n} iff 3|n.

    The proof is algebraic:
    Dividing by ζ^a: 1 + ζ^p + ζ^q = 0 where p=b-a, q=c-a (mod n).
    Setting α = ζ^p: then ζ^q = -1-α.
    For ζ^q to be an nth root of unity: |-1-α| = 1.
    |-1-α|² = 1 + 2Re(α) + |α|² = 2 + 2cos(2πp/n).
    Setting = 1: cos(2πp/n) = -1/2, so p/n = ±1/3.
    This requires n | 3p, i.e., gcd allows p = n/3 or 2n/3 → need 3|n.
    """
    print("=" * 70)
    print("PHASE 1: THREE-TERM VANISHING SUM CHARACTERIZATION")
    print("=" * 70)
    print()
    print("Theorem: For ζ = e^{2πi/n}, the equation ζ^a + ζ^b + ζ^c = 0")
    print("has a solution (a,b,c with 0 ≤ a,b,c < n) if and only if 3|n.")
    print()
    print("Proof sketch:")
    print("  WLOG divide by ζ^a: 1 + ζ^p + ζ^q = 0")
    print("  Set α = ζ^p. Then ζ^q = -1-α must satisfy |ζ^q| = 1.")
    print("  |-1-α|² = 2 + 2cos(2πp/n) = 1  ⟹  cos(2πp/n) = -1/2")
    print("  ⟹  p/n ∈ {1/3, 2/3}  ⟹  3|n.  □")
    print()

    # Verify computationally
    print("Computational verification (n = 2..{}):".format(n_max))
    all_match = True
    for n in range(2, n_max + 1):
        zeta = cmath.exp(2j * cmath.pi / n)
        has_vanishing = False
        for p in range(n):
            for q in range(p, n):
                val = 1 + zeta**p + zeta**q
                if abs(val) < TOL:
                    has_vanishing = True
                    break
            if has_vanishing:
                break
        expected = (n % 3 == 0)
        if has_vanishing != expected:
            print(f"  MISMATCH at n={n}: found={has_vanishing}, expected={expected}")
            all_match = False

    if all_match:
        print(f"  ✓ Verified for all n=2..{n_max}: vanishing sum iff 3|n")
    print()

    # Two-term vanishing sums
    print("Two-term vanishing sums: ζ^a + ζ^b = 0  ⟺  ζ^(b-a) = -1  ⟺  2|n")
    print("Verification:")
    all_match_2 = True
    for n in range(2, n_max + 1):
        zeta = cmath.exp(2j * cmath.pi / n)
        has_neg = any(abs(zeta**k + 1) < TOL for k in range(n))
        expected = (n % 2 == 0)
        if has_neg != expected:
            print(f"  MISMATCH at n={n}")
            all_match_2 = False
    if all_match_2:
        print(f"  ✓ Verified for all n=2..{n_max}: ζ^k = -1 iff 2|n")
    print()

    return all_match and all_match_2


