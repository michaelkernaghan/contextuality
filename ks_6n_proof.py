# PHASE 5: The interlocking mechanism — comparing 6|n vs not
# ============================================================

def interlocking_comparison():
    """
    Compare structural properties of 6|n pools vs non-6|n pools
    to identify what makes interlocking work.
    """
    print("=" * 70)
    print("PHASE 5: INTERLOCKING MECHANISM — 6|n vs NOT")
    print("=" * 70)
    print()

    test_cases = [
        (6, True), (9, False), (12, True), (15, False),
        (18, True), (21, False), (24, True), (27, False),
        (30, True), (33, False),
    ]

    print(f"  {'n':>4s}  {'6|n':>3s}  {'rays':>5s}  {'pairs':>5s}  {'triads':>6s}  "
          f"{'t/r':>5s}  {'p/r':>5s}  {'pair-only':>9s}  {'triad-conn':>10s}  {'max-deg':>7s}")
    print("  " + "-" * 85)

    for n, is_6n in test_cases:
        rays = generate_cyclotomic_pool(n)
        pairs, triads, adj = build_orthogonality(rays)
        nr = len(rays)

        # Triad connectivity
        triad_rays = set()
        for a, b, c in triads:
            triad_rays.update([a, b, c])

        pair_rays = set()
        for u, v in pairs:
            pair_rays.update([u, v])
        pair_only = len(pair_rays - triad_rays)

        # Max degree in orthogonality graph
        max_deg = max((len(adj[i]) for i in range(nr)), default=0)

        # Triad overlap density
        triad_pairs_shared = 0
        for i, (a1, b1, c1) in enumerate(triads):
            s1 = {a1, b1, c1}
            for j in range(i+1, len(triads)):
                a2, b2, c2 = triads[j]
                if s1 & {a2, b2, c2}:
                    triad_pairs_shared += 1
        triad_conn = triad_pairs_shared / max(len(triads), 1)

        tag = "Y" if is_6n else "N"
        print(f"  {n:4d}  {tag:>3s}  {nr:5d}  {len(pairs):5d}  {len(triads):6d}  "
              f"{len(triads)/nr:5.2f}  {len(pairs)/nr:5.1f}  {pair_only:9d}  "
              f"{triad_conn:10.1f}  {max_deg:7d}")

    print()


