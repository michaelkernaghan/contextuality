# PHASE 4: Explicit coloring for 3|n, 2∤n
# ============================================================

def find_explicit_coloring(n):
    """Find and display an explicit valid KS coloring for odd 3|n pool."""
    rays = generate_cyclotomic_pool(n)
    pairs, triads, adj = build_orthogonality(rays)

    from pysat.solvers import Glucose4

    clauses = []
    for (a, b, c) in triads:
        va, vb, vc = a+1, b+1, c+1
        clauses.append([va, vb, vc])
        clauses.append([-va, -vb])
        clauses.append([-va, -vc])
        clauses.append([-vb, -vc])
    for (u, v) in pairs:
        clauses.append([-(u+1), -(v+1)])

    with Glucose4(bootstrap_with=clauses) as solver:
        if solver.solve():
            model = solver.get_model()
            green = [i for i in range(len(rays)) if model[i] > 0]
            return len(green), len(rays), len(triads)
    return None


def explicit_colorings_phase():
    """Show that every odd multiple of 3 admits a valid coloring."""
    print("=" * 70)
    print("PHASE 4: EXPLICIT COLORINGS FOR 3|n, 2∤n")
    print("=" * 70)
    print()

    for n in [3, 9, 15, 21, 27, 33, 39, 45, 51, 57, 63]:
        if n % 3 != 0 or n % 2 == 0:
            continue
        result = find_explicit_coloring(n)
        if result:
            green, total, triads = result
            print(f"  n={n:3d}: COLORABLE  ({green} green / {total} rays, {triads} triads)")
        else:
            print(f"  n={n:3d}: UNCOLORABLE  ← would disprove conjecture!")


