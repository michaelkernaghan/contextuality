# PHASE 3: Why 3|n but 2∤n fails (structural analysis)
# ============================================================

def analyze_odd_multiples_of_3(n_values=None):
    """
    For n with 3|n but 2∤n, analyze why the pool is colorable.

    Key question: These pools have triads (from 1+ω+ω²=0).
    Why don't the triads interlock enough for KS-uncolorability?
    """
    print("=" * 70)
    print("PHASE 3: WHY 3|n BUT 2∤n IS COLORABLE")
    print("=" * 70)
    print()

    if n_values is None:
        n_values = [3, 9, 15, 21, 27, 33, 39, 45]

    for n in n_values:
        assert n % 3 == 0 and n % 2 != 0

        rays = generate_cyclotomic_pool(n)
        pairs, triads, adj = build_orthogonality(rays)

        # Analyze triad structure
        # Count rays participating in triads
        triad_rays = set()
        for a, b, c in triads:
            triad_rays.update([a, b, c])

        # Count rays participating in pairs but not triads
        pair_only_rays = set()
        for u, v in pairs:
            pair_only_rays.update([u, v])
        pair_only_rays -= triad_rays

        # Triad connectivity: build triad overlap graph
        triad_adj = {}  # triad_idx -> set of triad_idxs sharing a ray
        for i, (a1, b1, c1) in enumerate(triads):
            triad_adj[i] = set()
            s1 = {a1, b1, c1}
            for j, (a2, b2, c2) in enumerate(triads):
                if j != i and s1 & {a2, b2, c2}:
                    triad_adj[i].add(j)

        # Triad connectivity components
        visited = set()
        components = []
        for start in range(len(triads)):
            if start in visited:
                continue
            comp = set()
            stack = [start]
            while stack:
                node = stack.pop()
                if node in visited:
                    continue
                visited.add(node)
                comp.add(node)
                stack.extend(triad_adj.get(node, set()) - visited)
            components.append(comp)

        # Average degree of rays in triads
        if triad_rays:
            avg_triad_deg = sum(len(adj[r] & triad_rays) for r in triad_rays) / len(triad_rays)
        else:
            avg_triad_deg = 0

        # Compare with 6|n: n and n+3 (the next even multiple)
        n_even = n + 3 if (n + 3) % 6 == 0 else n + 3
        # Actually just compare ratios
        triad_density = len(triads) / max(len(rays), 1)

        print(f"  n={n}: {len(rays)} rays, {len(pairs)} pairs, {len(triads)} triads")
        print(f"    Rays in triads: {len(triad_rays)}/{len(rays)} ({100*len(triad_rays)/len(rays):.0f}%)")
        print(f"    Rays in pairs only: {len(pair_only_rays)}")
        print(f"    Triad components: {len(components)} (sizes: {sorted([len(c) for c in components], reverse=True)[:5]})")
        print(f"    Avg triad-ray degree: {avg_triad_deg:.1f}")
        print(f"    Triads/ray ratio: {triad_density:.3f}")

        # Key structural feature: check for "isolated" triads
        isolated = sum(1 for i in range(len(triads)) if len(triad_adj.get(i, set())) == 0)
        print(f"    Isolated triads (no shared ray with another): {isolated}/{len(triads)}")

        # Check: does any ray appear in 3+ triads? (needed for interlocking)
        from collections import Counter
        ray_triad_count = Counter()
        for a, b, c in triads:
            ray_triad_count[a] += 1
            ray_triad_count[b] += 1
            ray_triad_count[c] += 1
        max_triad_membership = max(ray_triad_count.values()) if ray_triad_count else 0
        rays_in_3plus = sum(1 for r, c in ray_triad_count.items() if c >= 3)
        print(f"    Max triad membership: {max_triad_membership}")
        print(f"    Rays in 3+ triads: {rays_in_3plus}")
        print()


