# Pool generation from nth roots of unity
# ============================================================

TOL = 1e-9

def generate_cyclotomic_pool(n):
    """Generate ray pool from nth roots of unity alphabet {0} ∪ {ζ^k}."""
    zeta = cmath.exp(2j * cmath.pi / n)
    alphabet = [0] + [zeta**k for k in range(n)]

    # Generate all nonzero vectors in alphabet^3
    raw = []
    for combo in itertools.product(range(len(alphabet)), repeat=3):
        v = tuple(alphabet[i] for i in combo)
        if all(abs(x) < TOL for x in v):
            continue
        raw.append(v)

    # Canonicalize: projective equivalence (v ~ λv for |λ|=1)
    canonical = []
    seen = set()
    for v in raw:
        # Find first nonzero coordinate, normalize by its phase
        for c in v:
            if abs(c) > TOL:
                phase = c / abs(c)
                break
        normed = tuple(x / phase for x in v)
        # Round for hashing
        key = tuple((round(x.real, 8), round(x.imag, 8)) for x in normed)
        if key not in seen:
            seen.add(key)
            canonical.append(normed)

    return canonical


def hermitian_dot(v, w):
    """Hermitian inner product <v|w> = Σ v̄_k w_k."""
    return sum(x.conjugate() * y for x, y in zip(v, w))


def build_orthogonality(rays):
    """Build pairs and triads from ray set."""
    n = len(rays)
    pairs = []
    adj = [set() for _ in range(n)]
    for i in range(n):
        for j in range(i+1, n):
            if abs(hermitian_dot(rays[i], rays[j])) < TOL:
                pairs.append((i, j))
                adj[i].add(j)
                adj[j].add(i)

    triads = []
    for i in range(n):
        for j in adj[i]:
            if j > i:
                common = adj[i] & adj[j]
                for k in common:
                    if k > j:
                        triads.append((i, j, k))

    return pairs, triads, adj


def is_ks_uncolorable(n_rays, triads, pairs):
    """SAT check for KS-uncolorability."""
    try:
        from pysat.solvers import Glucose4
        from pysat.card import CardEnc, EncType
    except ImportError:
        return _backtrack_check(n_rays, triads, pairs)

    clauses = []
    for (a, b, c) in triads:
        va, vb, vc = a+1, b+1, c+1
        clauses.append([va, vb, vc])  # at least one
        clauses.append([-va, -vb])
        clauses.append([-va, -vc])
        clauses.append([-vb, -vc])

    for (u, v) in pairs:
        vu, vv = u+1, v+1
        clauses.append([-vu, -vv])

    with Glucose4(bootstrap_with=clauses) as solver:
        return not solver.solve()


def _backtrack_check(n_rays, triads, pairs):
    """Fallback backtracking coloring check."""
    adj_pairs = [set() for _ in range(n_rays)]
    for u, v in pairs:
        adj_pairs[u].add(v)
        adj_pairs[v].add(u)

    triad_map = [[] for _ in range(n_rays)]
    for idx, (a, b, c) in enumerate(triads):
        triad_map[a].append(idx)
        triad_map[b].append(idx)
        triad_map[c].append(idx)

    color = [None] * n_rays  # None=unset, 1=green, 0=red

    def propagate():
        changed = True
        while changed:
            changed = False
            for idx, (a, b, c) in enumerate(triads):
                vals = [color[a], color[b], color[c]]
                greens = vals.count(1)
                reds = vals.count(0)
                if greens > 1:
                    return False
                if greens == 1 and reds < 2:
                    for x in (a, b, c):
                        if color[x] is None:
                            color[x] = 0
                            changed = True
                if reds == 2 and greens == 0:
                    for x in (a, b, c):
                        if color[x] is None:
                            color[x] = 1
                            changed = True
            for u, v in pairs:
                if color[u] == 1 and color[v] == 1:
                    return False
                if color[u] == 1 and color[v] is None:
                    color[v] = 0
                    changed = True
                if color[v] == 1 and color[u] is None:
                    color[u] = 0
                    changed = True
        return True

    def solve(idx):
        if idx == n_rays:
            return True
        if color[idx] is not None:
            return solve(idx + 1)
        for c_val in [1, 0]:
            saved = color[:]
            color[idx] = c_val
            if propagate() and solve(idx + 1):
                return True
            for i in range(n_rays):
                color[i] = saved[i]
        return False

    return not (propagate() and solve(0))


